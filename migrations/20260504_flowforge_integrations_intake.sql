CREATE TABLE IF NOT EXISTS flowforge_integration_configs (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  workspace_id VARCHAR(128) NOT NULL,
  provider VARCHAR(64) NOT NULL,
  integration_key VARCHAR(128) NOT NULL,
  display_name VARCHAR(255) NOT NULL,
  external_form_id VARCHAR(255) NULL,
  enabled TINYINT(1) NOT NULL DEFAULT 1,
  mode VARCHAR(16) NOT NULL DEFAULT 'production',
  webhook_public_id VARCHAR(128) NOT NULL,
  secret_hash VARCHAR(255) NOT NULL,
  secret_last_rotated_by VARCHAR(255) NULL,
  secret_last_rotated_at DATETIME NULL,
  field_mapping_json JSON NULL,
  test_recipient_overrides_json JSON NULL,
  settings_json JSON NULL,
  created_by VARCHAR(255) NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_by VARCHAR(255) NULL,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  disabled_by VARCHAR(255) NULL,
  disabled_at DATETIME NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uidx_ff_integration_key (workspace_id, integration_key),
  UNIQUE KEY uidx_ff_webhook_public_id (webhook_public_id),
  KEY idx_ff_integration_workspace_provider (workspace_id, provider),
  KEY idx_ff_integration_form (workspace_id, provider, external_form_id),
  KEY idx_ff_integration_enabled (workspace_id, enabled)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS flowforge_integration_triggers (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  workspace_id VARCHAR(128) NOT NULL,
  integration_config_id BIGINT UNSIGNED NOT NULL,
  trigger_key VARCHAR(128) NOT NULL,
  display_name VARCHAR(255) NOT NULL,
  enabled TINYINT(1) NOT NULL DEFAULT 1,
  priority INT UNSIGNED NOT NULL DEFAULT 100,
  trigger_mode VARCHAR(32) NOT NULL DEFAULT 'always',
  trigger_policy VARCHAR(32) NOT NULL DEFAULT 'all_matching',
  version_strategy VARCHAR(32) NOT NULL DEFAULT 'pinned',
  workflow_definition_id BIGINT UNSIGNED NOT NULL,
  workflow_version_id BIGINT UNSIGNED NULL,
  condition_json JSON NULL,
  field_mapping_json JSON NULL,
  no_match_config_json JSON NULL,
  created_by VARCHAR(255) NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_by VARCHAR(255) NULL,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uidx_ff_trigger_key (integration_config_id, trigger_key),
  KEY idx_ff_trigger_integration (workspace_id, integration_config_id, enabled, priority),
  KEY idx_ff_trigger_workflow (workspace_id, workflow_definition_id, workflow_version_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS flowforge_intake_events (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  workspace_id VARCHAR(128) NOT NULL,
  integration_config_id BIGINT UNSIGNED NOT NULL,
  provider VARCHAR(64) NOT NULL,
  external_form_id VARCHAR(255) NULL,
  external_submission_id VARCHAR(255) NULL,
  mode VARCHAR(16) NOT NULL DEFAULT 'production',
  idempotency_key VARCHAR(255) NOT NULL,
  received_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  source_ip VARCHAR(64) NULL,
  headers_json JSON NULL,
  raw_payload_json JSON NULL,
  normalized_payload_json JSON NOT NULL,
  sensitive_fields_json JSON NULL,
  trigger_evaluation_json JSON NULL,
  status VARCHAR(32) NOT NULL DEFAULT 'received',
  error_code VARCHAR(128) NULL,
  error_message VARCHAR(512) NULL,
  raw_payload_expires_at DATETIME NULL,
  raw_payload_redacted_at DATETIME NULL,
  raw_payload_redacted_by VARCHAR(255) NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uidx_ff_intake_idempotency (workspace_id, idempotency_key),
  KEY idx_ff_intake_workspace_received (workspace_id, received_at),
  KEY idx_ff_intake_integration_received (integration_config_id, received_at),
  KEY idx_ff_intake_external (workspace_id, provider, external_form_id, external_submission_id),
  KEY idx_ff_intake_status (workspace_id, status),
  KEY idx_ff_intake_mode (workspace_id, mode),
  KEY idx_ff_intake_retention (raw_payload_expires_at, raw_payload_redacted_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS flowforge_intake_event_replays (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  workspace_id VARCHAR(128) NOT NULL,
  intake_event_id BIGINT UNSIGNED NOT NULL,
  requested_by VARCHAR(255) NULL,
  requested_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  reason TEXT NULL,
  status VARCHAR(32) NOT NULL DEFAULT 'pending',
  result_json JSON NULL,
  completed_at DATETIME NULL,
  PRIMARY KEY (id),
  KEY idx_ff_intake_replay_event (workspace_id, intake_event_id),
  KEY idx_ff_intake_replay_status (workspace_id, status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
