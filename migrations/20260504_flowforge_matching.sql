CREATE TABLE IF NOT EXISTS flowforge_matching_policies (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  workspace_id VARCHAR(128) NOT NULL,
  policy_key VARCHAR(128) NOT NULL,
  display_name VARCHAR(255) NOT NULL,
  description TEXT NULL,
  resource_set_id BIGINT UNSIGNED NOT NULL,
  status VARCHAR(32) NOT NULL DEFAULT 'draft',
  current_draft_version_id BIGINT UNSIGNED NULL,
  latest_published_version_id BIGINT UNSIGNED NULL,
  created_by VARCHAR(255) NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_by VARCHAR(255) NULL,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  archived_at DATETIME NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uidx_ff_matching_policy_key (workspace_id, policy_key),
  KEY idx_ff_matching_policy_resource_set (workspace_id, resource_set_id),
  KEY idx_ff_matching_policy_status (workspace_id, status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS flowforge_matching_policy_versions (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  workspace_id VARCHAR(128) NOT NULL,
  matching_policy_id BIGINT UNSIGNED NOT NULL,
  resource_set_id BIGINT UNSIGNED NOT NULL,
  version_number INT UNSIGNED NOT NULL,
  version_status VARCHAR(32) NOT NULL DEFAULT 'draft',
  policy_json JSON NOT NULL,
  validation_status VARCHAR(32) NOT NULL DEFAULT 'pending',
  validation_result_json JSON NULL,
  explanation_template_json JSON NULL,
  created_by VARCHAR(255) NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  published_by VARCHAR(255) NULL,
  published_at DATETIME NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uidx_ff_matching_policy_version (matching_policy_id, version_number),
  KEY idx_ff_matching_policy_version_workspace (workspace_id, matching_policy_id),
  KEY idx_ff_matching_policy_version_status (workspace_id, version_status),
  KEY idx_ff_matching_policy_version_resource_set (workspace_id, resource_set_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS flowforge_matching_policy_llm_drafts (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  workspace_id VARCHAR(128) NOT NULL,
  matching_policy_id BIGINT UNSIGNED NULL,
  resource_set_id BIGINT UNSIGNED NOT NULL,
  prompt TEXT NOT NULL,
  generated_policy_json JSON NULL,
  plain_language_summary TEXT NULL,
  validation_status VARCHAR(32) NOT NULL DEFAULT 'pending',
  validation_result_json JSON NULL,
  model_provider VARCHAR(64) NULL,
  model_name VARCHAR(128) NULL,
  status VARCHAR(32) NOT NULL DEFAULT 'drafted',
