CREATE TABLE IF NOT EXISTS flowforge_matching_simulations (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  workspace_id VARCHAR(128) NOT NULL,
  matching_policy_version_id BIGINT UNSIGNED NULL,
  resource_set_id BIGINT UNSIGNED NOT NULL,
  snapshot_batch_id BIGINT UNSIGNED NULL,
  input_context_json JSON NOT NULL,
  result_json JSON NULL,
  status VARCHAR(32) NOT NULL DEFAULT 'pending',
  created_by VARCHAR(255) NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  completed_at DATETIME NULL,
  PRIMARY KEY (id),
  KEY idx_ff_sim_policy (workspace_id, matching_policy_version_id),
  KEY idx_ff_sim_resource_set (workspace_id, resource_set_id),
  KEY idx_ff_sim_created (workspace_id, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS flowforge_matching_evaluations (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  workspace_id VARCHAR(128) NOT NULL,
  run_id BIGINT UNSIGNED NULL,
  matching_policy_version_id BIGINT UNSIGNED NOT NULL,
  resource_set_id BIGINT UNSIGNED NOT NULL,
  snapshot_batch_id BIGINT UNSIGNED NOT NULL,
  input_context_json JSON NOT NULL,
  summary_json JSON NULL,
  selected_source_record_key VARCHAR(255) NULL,
  no_match_reason VARCHAR(255) NULL,
  status VARCHAR(32) NOT NULL DEFAULT 'completed',
  evaluated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_ff_eval_run (workspace_id, run_id),
  KEY idx_ff_eval_policy (workspace_id, matching_policy_version_id),
  KEY idx_ff_eval_resource_set (workspace_id, resource_set_id),
  KEY idx_ff_eval_no_match (workspace_id, no_match_reason),
  KEY idx_ff_eval_selected (workspace_id, selected_source_record_key)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS flowforge_matching_evaluation_candidates (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  workspace_id VARCHAR(128) NOT NULL,
  matching_evaluation_id BIGINT UNSIGNED NOT NULL,
  resource_set_id BIGINT UNSIGNED NOT NULL,
  source_record_key VARCHAR(255) NOT NULL,
  included TINYINT(1) NOT NULL DEFAULT 0,
  excluded TINYINT(1) NOT NULL DEFAULT 0,
  selected TINYINT(1) NOT NULL DEFAULT 0,
  rank_position INT UNSIGNED NULL,
  score DECIMAL(12,4) NULL,
  eligibility_result_json JSON NULL,
  score_breakdown_json JSON NULL,
  explanation_json JSON NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uidx_ff_eval_candidate (matching_evaluation_id, source_record_key),
  KEY idx_ff_eval_candidate_rank (workspace_id, matching_evaluation_id, rank_position),
  KEY idx_ff_eval_candidate_selected (workspace_id, selected),
  KEY idx_ff_eval_candidate_resource (workspace_id, resource_set_id, source_record_key)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
