CREATE TABLE IF NOT EXISTS flowforge_resource_sets (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  workspace_id VARCHAR(128) NOT NULL,
  resource_set_key VARCHAR(128) NOT NULL,
  display_name VARCHAR(255) NOT NULL,
  description TEXT NULL,
  source_type VARCHAR(64) NOT NULL DEFAULT 'manual_csv',
  enabled TINYINT(1) NOT NULL DEFAULT 1,
  active_snapshot_batch_id BIGINT UNSIGNED NULL,
  mapping_version_id BIGINT UNSIGNED NULL,
  refresh_schedule_json JSON NULL,
  settings_json JSON NULL,
  created_by VARCHAR(255) NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_by VARCHAR(255) NULL,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  archived_at DATETIME NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uidx_ff_resource_set_key (workspace_id, resource_set_key),
  KEY idx_ff_resource_set_workspace_enabled (workspace_id, enabled),
  KEY idx_ff_resource_set_source (workspace_id, source_type)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS flowforge_resource_mappings (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  workspace_id VARCHAR(128) NOT NULL,
  resource_set_id BIGINT UNSIGNED NOT NULL,
  version_number INT UNSIGNED NOT NULL,
  source_type VARCHAR(64) NOT NULL,
  source_ref_json JSON NULL,
  mapping_json JSON NOT NULL,
  validation_status VARCHAR(32) NOT NULL DEFAULT 'pending',
  validation_result_json JSON NULL,
  created_by VARCHAR(255) NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  activated_by VARCHAR(255) NULL,
  activated_at DATETIME NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uidx_ff_resource_mapping_version (resource_set_id, version_number),
  KEY idx_ff_resource_mapping_set (workspace_id, resource_set_id),
  KEY idx_ff_resource_mapping_status (workspace_id, validation_status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS flowforge_resource_snapshot_batches (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  workspace_id VARCHAR(128) NOT NULL,
  resource_set_id BIGINT UNSIGNED NOT NULL,
  mapping_id BIGINT UNSIGNED NULL,
  batch_key VARCHAR(128) NOT NULL,
  source_type VARCHAR(64) NOT NULL,
  mode VARCHAR(16) NOT NULL DEFAULT 'production',
  status VARCHAR(32) NOT NULL DEFAULT 'pending',
  record_count INT UNSIGNED NOT NULL DEFAULT 0,
  valid_count INT UNSIGNED NOT NULL DEFAULT 0,
  invalid_count INT UNSIGNED NOT NULL DEFAULT 0,
  source_ref_json JSON NULL,
  summary_json JSON NULL,
  started_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  completed_at DATETIME NULL,
  created_by VARCHAR(255) NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uidx_ff_snapshot_batch_key (resource_set_id, batch_key),
  KEY idx_ff_snapshot_batch_set_status (workspace_id, resource_set_id, status),
  KEY idx_ff_snapshot_batch_started (workspace_id, started_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS flowforge_resource_snapshot_records (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  workspace_id VARCHAR(128) NOT NULL,
  resource_set_id BIGINT UNSIGNED NOT NULL,
  snapshot_batch_id BIGINT UNSIGNED NOT NULL,
  source_record_key VARCHAR(255) NOT NULL,
  display_name VARCHAR(255) NULL,
  primary_email VARCHAR(255) NULL,
  primary_phone VARCHAR(64) NULL,
  status VARCHAR(32) NOT NULL DEFAULT 'active',
  source_status VARCHAR(64) NULL,
  effective_status VARCHAR(32) NOT NULL DEFAULT 'active',
  availability_status VARCHAR(32) NULL,
  capacity_total DECIMAL(12,2) NULL,
  capacity_used DECIMAL(12,2) NULL,
  capacity_available DECIMAL(12,2) NULL,
  current_load DECIMAL(12,2) NULL,
  service_area VARCHAR(255) NULL,
  timezone VARCHAR(64) NULL,
  tags_json JSON NULL,
  attributes_json JSON NULL,
  normalized_profile_json JSON NOT NULL,
  sensitive_profile_json JSON NULL,
  validation_status VARCHAR(32) NOT NULL DEFAULT 'valid',
  validation_errors_json JSON NULL,
  source_missing TINYINT(1) NOT NULL DEFAULT 0,
  compiled_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  source_updated_at DATETIME NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uidx_ff_resource_snapshot_source (snapshot_batch_id, source_record_key),
  KEY idx_ff_resource_snapshot_set_status (workspace_id, resource_set_id, effective_status),
  KEY idx_ff_resource_snapshot_batch (workspace_id, resource_set_id, snapshot_batch_id),
  KEY idx_ff_resource_snapshot_email (workspace_id, primary_email),
  KEY idx_ff_resource_snapshot_availability (workspace_id, resource_set_id, availability_status),
  KEY idx_ff_resource_snapshot_capacity (workspace_id, resource_set_id, capacity_available),
  KEY idx_ff_resource_snapshot_source_missing (workspace_id, resource_set_id, source_missing)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS flowforge_resource_overrides (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  workspace_id VARCHAR(128) NOT NULL,
  resource_set_id BIGINT UNSIGNED NOT NULL,
  source_record_key VARCHAR(255) NOT NULL,
  override_type VARCHAR(64) NOT NULL,
  override_json JSON NOT NULL,
  reason TEXT NULL,
  enabled TINYINT(1) NOT NULL DEFAULT 1,
  effective_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  expires_at DATETIME NULL,
  created_by VARCHAR(255) NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  revoked_by VARCHAR(255) NULL,
  revoked_at DATETIME NULL,
  PRIMARY KEY (id),
  KEY idx_ff_resource_override_resource (workspace_id, resource_set_id, source_record_key, enabled),
  KEY idx_ff_resource_override_expiry (workspace_id, expires_at),
  KEY idx_ff_resource_override_type (workspace_id, override_type)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS flowforge_resource_runtime_state (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  workspace_id VARCHAR(128) NOT NULL,
  resource_set_id BIGINT UNSIGNED NOT NULL,
  source_record_key VARCHAR(255) NOT NULL,
  active_offer_count INT UNSIGNED NOT NULL DEFAULT 0,
  active_assignment_count INT UNSIGNED NOT NULL DEFAULT 0,
  cooldown_until DATETIME NULL,
  last_offered_at DATETIME NULL,
  last_accepted_at DATETIME NULL,
  last_declined_at DATETIME NULL,
  fairness_score DECIMAL(12,4) NULL,
  state_json JSON NULL,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uidx_ff_runtime_resource (workspace_id, resource_set_id, source_record_key),
  KEY idx_ff_runtime_cooldown (workspace_id, resource_set_id, cooldown_until),
  KEY idx_ff_runtime_offer_count (workspace_id, resource_set_id, active_offer_count)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
