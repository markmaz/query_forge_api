CREATE TABLE IF NOT EXISTS flowforge_dataset_artifacts (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  workspace_id VARCHAR(128) NOT NULL,
  run_id BIGINT UNSIGNED NULL,
  node_id VARCHAR(128) NULL,
  artifact_key VARCHAR(255) NOT NULL,
  artifact_type VARCHAR(64) NOT NULL,
  storage_kind VARCHAR(64) NOT NULL DEFAULT 'metadata_only',
  storage_ref_json JSON NULL,
  schema_json JSON NULL,
  row_count BIGINT UNSIGNED NULL,
  byte_count BIGINT UNSIGNED NULL,
  checksum VARCHAR(128) NULL,
  status VARCHAR(32) NOT NULL DEFAULT 'ready',
  expires_at DATETIME NULL,
  created_by VARCHAR(255) NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uidx_ff_dataset_artifact_key (workspace_id, artifact_key),
  KEY idx_ff_dataset_artifact_workspace_status (workspace_id, status),
  KEY idx_ff_dataset_artifact_run (workspace_id, run_id),
  KEY idx_ff_dataset_artifact_created (workspace_id, created_at),
  KEY idx_ff_dataset_artifact_expiry (expires_at, status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS flowforge_data_movement_audit (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  workspace_id VARCHAR(128) NOT NULL,
  run_id BIGINT UNSIGNED NULL,
  node_id VARCHAR(128) NULL,
  action_type VARCHAR(64) NOT NULL,
  status VARCHAR(32) NOT NULL,
  source_key VARCHAR(128) NULL,
  destination_key VARCHAR(128) NULL,
  dataset_artifact_id BIGINT UNSIGNED NULL,
  resource_set_id BIGINT UNSIGNED NULL,
  actor_type VARCHAR(32) NULL,
  actor_id VARCHAR(255) NULL,
  request_json JSON NULL,
  result_json JSON NULL,
  error_message VARCHAR(512) NULL,
  idempotency_key VARCHAR(255) NULL,
  started_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  completed_at DATETIME NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uidx_ff_data_movement_audit_idempotency (workspace_id, idempotency_key),
  KEY idx_ff_data_movement_audit_run (workspace_id, run_id, started_at),
  KEY idx_ff_data_movement_audit_action_status (workspace_id, action_type, status),
  KEY idx_ff_data_movement_audit_artifact (workspace_id, dataset_artifact_id),
  KEY idx_ff_data_movement_audit_source (workspace_id, source_key),
  KEY idx_ff_data_movement_audit_destination (workspace_id, destination_key)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS flowforge_data_sources (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  workspace_id VARCHAR(128) NOT NULL,
  source_key VARCHAR(128) NOT NULL,
  display_name VARCHAR(255) NOT NULL,
  source_type VARCHAR(64) NOT NULL,
  enabled TINYINT(1) NOT NULL DEFAULT 1,
  mode VARCHAR(16) NOT NULL DEFAULT 'test',
  config_json JSON NULL,
  created_by VARCHAR(255) NULL,
  updated_by VARCHAR(255) NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  archived_at DATETIME NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uidx_ff_data_source_key (workspace_id, source_key),
  KEY idx_ff_data_source_workspace_enabled (workspace_id, enabled),
  KEY idx_ff_data_source_type (workspace_id, source_type),
  KEY idx_ff_data_source_archived (workspace_id, archived_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

