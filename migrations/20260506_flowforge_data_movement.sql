CREATE TABLE IF NOT EXISTS flowforge_schedule_runs (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  workspace_id VARCHAR(128) NOT NULL,
  workflow_definition_id BIGINT UNSIGNED NOT NULL,
  workflow_version_id BIGINT UNSIGNED NULL,
  trigger_node_id VARCHAR(128) NOT NULL,
  schedule_key VARCHAR(128) NOT NULL,
  scheduled_for DATETIME NOT NULL,
  window_start DATETIME NOT NULL,
  window_end DATETIME NULL,
  status VARCHAR(32) NOT NULL DEFAULT 'pending',
  run_id BIGINT UNSIGNED NULL,
  idempotency_key VARCHAR(255) NOT NULL,
  trigger_payload_json JSON NULL,
  error_message VARCHAR(512) NULL,
  started_at DATETIME NULL,
  completed_at DATETIME NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uidx_ff_schedule_run_idempotency (workspace_id, idempotency_key),
  KEY idx_ff_schedule_run_due (workspace_id, status, scheduled_for),
  KEY idx_ff_schedule_run_trigger (workspace_id, workflow_definition_id, trigger_node_id, scheduled_for),
  KEY idx_ff_schedule_run_workflow (workspace_id, workflow_definition_id, workflow_version_id),
  KEY idx_ff_schedule_run_run (workspace_id, run_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
