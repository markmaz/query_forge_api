CREATE TABLE IF NOT EXISTS flowforge_communication_template_ai_drafts (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  workspace_id VARCHAR(128) NOT NULL,
  purpose VARCHAR(32) NOT NULL DEFAULT 'notification',
  channel VARCHAR(32) NOT NULL DEFAULT 'email',
  resource_set_id BIGINT UNSIGNED NULL,
  prompt TEXT NOT NULL,
  tone VARCHAR(64) NULL,
  required_actions_json JSON NOT NULL,
  generated_subject TEXT NOT NULL,
  generated_body_blocks_json JSON NOT NULL,
  plain_language_summary TEXT NULL,
  validation_status VARCHAR(32) NOT NULL DEFAULT 'pending',
  validation_result_json JSON NOT NULL,
  model_provider VARCHAR(64) NULL,
  model_name VARCHAR(255) NULL,
  status VARCHAR(32) NOT NULL DEFAULT 'drafted',
  created_by VARCHAR(128) NULL,
  reviewed_by VARCHAR(128) NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  reviewed_at DATETIME NULL,
  PRIMARY KEY (id),
  KEY idx_ff_comm_template_ai_draft_workspace (workspace_id, created_at),
  KEY idx_ff_comm_template_ai_draft_resource (workspace_id, resource_set_id),
  KEY idx_ff_comm_template_ai_draft_purpose (workspace_id, purpose, channel)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
