CREATE TABLE IF NOT EXISTS flowforge_communication_templates (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  workspace_id VARCHAR(128) NOT NULL,
  template_key VARCHAR(128) NOT NULL,
  display_name VARCHAR(255) NOT NULL,
  description TEXT NULL,
  channel VARCHAR(32) NOT NULL DEFAULT 'email',
  purpose VARCHAR(32) NOT NULL DEFAULT 'notification',
  resource_set_id BIGINT UNSIGNED NULL,
  subject TEXT NOT NULL,
  body_blocks_json JSON NOT NULL,
  status VARCHAR(32) NOT NULL DEFAULT 'draft',
  validation_status VARCHAR(32) NOT NULL DEFAULT 'pending',
  validation_result_json JSON NOT NULL,
  metadata_json JSON NOT NULL,
  created_by VARCHAR(128) NULL,
  updated_by VARCHAR(128) NULL,
  activated_by VARCHAR(128) NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  activated_at DATETIME NULL,
  archived_at DATETIME NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uidx_ff_comm_template_key (workspace_id, template_key),
  KEY idx_ff_comm_template_workspace_status (workspace_id, status),
  KEY idx_ff_comm_template_workspace_purpose (workspace_id, purpose, channel),
  KEY idx_ff_comm_template_resource_set (workspace_id, resource_set_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
