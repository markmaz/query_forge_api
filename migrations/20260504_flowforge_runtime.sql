CREATE TABLE IF NOT EXISTS flowforge_runs (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  workspace_id VARCHAR(128) NOT NULL,
  workflow_definition_id BIGINT UNSIGNED NOT NULL,
  workflow_version_id BIGINT UNSIGNED NOT NULL,
  intake_event_id BIGINT UNSIGNED NULL,
  mode VARCHAR(16) NOT NULL DEFAULT 'production',
  status VARCHAR(32) NOT NULL DEFAULT 'waiting',
  current_node_id VARCHAR(128) NULL,
  idempotency_key VARCHAR(255) NOT NULL,
  run_context_json JSON NULL,
  started_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  completed_at DATETIME NULL,
  failed_at DATETIME NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uidx_ff_run_idempotency (workspace_id, idempotency_key),
  KEY idx_ff_run_workspace_status (workspace_id, status),
  KEY idx_ff_run_workflow (workspace_id, workflow_definition_id, workflow_version_id),
  KEY idx_ff_run_intake (workspace_id, intake_event_id),
  KEY idx_ff_run_started (workspace_id, started_at),
  KEY idx_ff_run_mode (workspace_id, mode)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS flowforge_run_events (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  workspace_id VARCHAR(128) NOT NULL,
  run_id BIGINT UNSIGNED NOT NULL,
  event_type VARCHAR(128) NOT NULL,
  node_id VARCHAR(128) NULL,
  message VARCHAR(512) NULL,
  event_payload_json JSON NULL,
  sensitive_payload_json JSON NULL,
  actor_type VARCHAR(32) NULL,
  actor_id VARCHAR(255) NULL,
  idempotency_key VARCHAR(255) NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uidx_ff_run_event_idempotency (workspace_id, idempotency_key),
  KEY idx_ff_run_event_run (workspace_id, run_id, created_at),
  KEY idx_ff_run_event_type (workspace_id, event_type),
  KEY idx_ff_run_event_actor (workspace_id, actor_type, actor_id),
  KEY idx_ff_run_event_created (workspace_id, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS flowforge_human_tasks (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  workspace_id VARCHAR(128) NOT NULL,
  run_id BIGINT UNSIGNED NOT NULL,
  task_type VARCHAR(64) NOT NULL,
  resource_set_id BIGINT UNSIGNED NULL,
  source_record_key VARCHAR(255) NULL,
  status VARCHAR(32) NOT NULL DEFAULT 'pending',
  assigned_to_principal_type VARCHAR(32) NULL,
  assigned_to_principal_id VARCHAR(255) NULL,
  due_at DATETIME NULL,
  completed_at DATETIME NULL,
  response_json JSON NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_ff_human_task_run (workspace_id, run_id),
  KEY idx_ff_human_task_status_due (workspace_id, status, due_at),
  KEY idx_ff_human_task_resource (workspace_id, resource_set_id, source_record_key)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS flowforge_signed_action_tokens (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  workspace_id VARCHAR(128) NOT NULL,
  human_task_id BIGINT UNSIGNED NOT NULL,
  token_hash VARCHAR(64) NOT NULL,
  allowed_actions_json JSON NOT NULL,
  expires_at DATETIME NOT NULL,
  used_at DATETIME NULL,
  used_action VARCHAR(64) NULL,
  used_ip VARCHAR(64) NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  revoked_at DATETIME NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uidx_ff_signed_token_hash (token_hash),
  KEY idx_ff_signed_token_task (workspace_id, human_task_id),
  KEY idx_ff_signed_token_expiry (expires_at, used_at, revoked_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS flowforge_notifications (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  workspace_id VARCHAR(128) NOT NULL,
  run_id BIGINT UNSIGNED NULL,
  human_task_id BIGINT UNSIGNED NULL,
  channel VARCHAR(32) NOT NULL DEFAULT 'email',
  recipient VARCHAR(255) NOT NULL,
  template_key VARCHAR(128) NOT NULL,
  status VARCHAR(32) NOT NULL DEFAULT 'pending',
  idempotency_key VARCHAR(255) NOT NULL,
  payload_summary_json JSON NULL,
  provider_message_id VARCHAR(255) NULL,
  error_message VARCHAR(512) NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  sent_at DATETIME NULL,
  failed_at DATETIME NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uidx_ff_notification_idempotency (workspace_id, idempotency_key),
  KEY idx_ff_notification_run (workspace_id, run_id),
  KEY idx_ff_notification_task (workspace_id, human_task_id),
  KEY idx_ff_notification_status (workspace_id, status),
  KEY idx_ff_notification_created (workspace_id, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
