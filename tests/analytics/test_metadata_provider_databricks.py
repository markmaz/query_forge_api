# tests/analytics/test_metadata_provider_databricks.py
from __future__ import annotations

import pytest
from unittest.mock import MagicMock


from app.adapters.analytics.databricks_metadata_provider import DatabricksMetadataProvider
from app.ports.sql_executor_abc import SQLExecutor


def _make_executor(rows: list[dict]) -> SQLExecutor:
    ex = MagicMock(spec=SQLExecutor)
    ex.execute.return_value = rows
    ex.get_dialect.return_value = "databricks"
    return ex


@pytest.fixture()
def executor():
    ex = MagicMock(spec=SQLExecutor)
    ex.get_dialect.return_value = "databricks"
    return ex


# --- list_tables ---

def test_list_tables_returns_tables():
    ex = _make_executor([
        {"table_name": "orders", "table_type": "TABLE", "comment": "Order data"},
        {"table_name": "v_orders", "table_type": "VIEW", "comment": None},
    ])
    provider = DatabricksMetadataProvider(executor=ex)
    result = provider.list_tables(catalog="main", schema="sales")

    assert len(result) == 2
    assert result[0]["table_name"] == "orders"
    assert result[1]["table_type"] == "VIEW"


def test_list_tables_queries_information_schema():
    ex = _make_executor([])
    provider = DatabricksMetadataProvider(executor=ex)
    provider.list_tables(catalog="main", schema="sales")

    call_sql = ex.execute.call_args[0][0]
    assert "information_schema" in call_sql.lower()
    assert "sales" in call_sql


def test_list_tables_no_catalog():
    ex = _make_executor([])
    provider = DatabricksMetadataProvider(executor=ex)
    provider.list_tables(catalog=None, schema="sales")

    call_sql = ex.execute.call_args[0][0]
    assert "information_schema" in call_sql.lower()


