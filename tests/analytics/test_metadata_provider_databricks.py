# --- profile_table_columns ---

_DEFAULT_OPTIONS = {
    "sample_percent": 0.10,
    "sample_row_cap": 200_000,
    "per_column_limit": 10,
    "max_distinct_for_top_values": 250,
    "max_string_length_for_top_values": 500,
    "profile_top_values_only_for_string_types": True,
    "skip_top_values_for_id_like_cols": True,
}

_COLUMNS = [
    {"column_name": "id", "data_type": "BIGINT", "is_nullable": False},
    {"column_name": "name", "data_type": "STRING", "is_nullable": True},
]


def test_profile_returns_per_column_stats():
    ex = MagicMock(spec=SQLExecutor)
    # First call: sample row count; second call: aggregation stats
    # Keys match the SQL aliases generated by profile_table_columns: null_{col}, dist_{col}
    ex.execute.side_effect = [
        [{"row_count": 1000}],
        [{"null_id": 0, "dist_id": 1000, "null_name": 10, "dist_name": 500}],
    ]
    ex.get_dialect.return_value = "databricks"
    provider = DatabricksMetadataProvider(executor=ex)

    result = provider.profile_table_columns(
        table_ref="main.sales.orders",
        columns=_COLUMNS,
        options=_DEFAULT_OPTIONS,
    )

    assert "id" in result
    assert "name" in result
    assert result["id"]["null_count"] == 0
    assert result["name"]["null_count"] == 10


def test_profile_captures_error_when_executor_raises():
    ex = MagicMock(spec=SQLExecutor)
    ex.execute.side_effect = RuntimeError("analytics boom")
    ex.get_dialect.return_value = "databricks"
    provider = DatabricksMetadataProvider(executor=ex)

    result = provider.profile_table_columns(
        table_ref="main.sales.orders",
        columns=_COLUMNS,
        options=_DEFAULT_OPTIONS,
    )

    # Should not raise; all columns get sample_error set
    for col in _COLUMNS:
        assert result[col["column_name"]]["sample_error"] is not None


def test_profile_skips_top_values_for_id_like_columns():
    ex = MagicMock(spec=SQLExecutor)
    # Two calls: count + agg (no third top-values call expected for id-like column)
    ex.execute.side_effect = [
        [{"row_count": 100}],
        [{"null_user_id": 0, "dist_user_id": 100}],
    ]
    ex.get_dialect.return_value = "databricks"
    provider = DatabricksMetadataProvider(executor=ex)

    id_col = [{"column_name": "user_id", "data_type": "BIGINT", "is_nullable": False}]
    result = provider.profile_table_columns(
        table_ref="main.sales.orders",
        columns=id_col,
        options={**_DEFAULT_OPTIONS, "skip_top_values_for_id_like_cols": True},
    )

    assert result["user_id"].get("top_values") in (None, [])
    # Executor called at most twice (count + agg) — NOT a third time for top values
    assert ex.execute.call_count <= 2


def test_profile_falls_back_to_sample_values_for_high_cardinality_columns():
    ex = MagicMock(spec=SQLExecutor)
    ex.execute.side_effect = [
        [{"row_count": 100}],
        [{"null_name": 0, "dist_name": 5000}],
        [{"val": "alpha"}, {"val": "beta"}],
    ]
    ex.get_dialect.return_value = "databricks"
    provider = DatabricksMetadataProvider(executor=ex)

    result = provider.profile_table_columns(
        table_ref="main.sales.people",
        columns=[{"column_name": "name", "data_type": "STRING", "is_nullable": True}],
        options={**_DEFAULT_OPTIONS, "skip_top_values_for_id_like_cols": False},
    )

    sample_sql = ex.execute.call_args_list[2][0][0]
    assert "SELECT DISTINCT" in sample_sql
    assert "GROUP BY" not in sample_sql
    assert result["name"]["top_values"] == ["alpha", "beta"]


# --- list_schemas ---

def test_list_schemas_without_catalog(executor):
    executor.execute.return_value = [
        {"schema_name": "asset"},
        {"schema_name": "raw"},
    ]
    provider = DatabricksMetadataProvider(executor=executor)
    result = provider.list_schemas(catalog=None)
    assert result == ["asset", "raw"]
    sql = executor.execute.call_args[0][0]
    assert "information_schema.tables" in sql
    assert "DISTINCT" in sql
    assert "table_catalog" not in sql


def test_list_schemas_with_catalog(executor):
    executor.execute.return_value = [
        {"schema_name": "finance"},
        {"schema_name": "sales"},
    ]
    provider = DatabricksMetadataProvider(executor=executor)
    result = provider.list_schemas(catalog="main")
    assert result == ["finance", "sales"]
    sql = executor.execute.call_args[0][0]
    assert "information_schema.tables" in sql
    assert "table_catalog = 'main'" in sql


def test_list_schemas_falls_back_to_show_schemas_when_information_schema_fails(executor):
    executor.execute.side_effect = [
        RuntimeError("information_schema unavailable"),
        [{"databaseName": "asset"}, {"databaseName": "raw"}],
    ]
    provider = DatabricksMetadataProvider(executor=executor)
    result = provider.list_schemas(catalog=None)

    assert result == ["asset", "raw"]
    assert executor.execute.call_count == 2
    first_sql = executor.execute.call_args_list[0][0][0]
    second_sql = executor.execute.call_args_list[1][0][0]
    assert "information_schema.tables" in first_sql
    assert second_sql.strip().upper() == "SHOW SCHEMAS"


def test_list_schemas_falls_back_when_information_schema_returns_empty_rows(executor):
    executor.execute.side_effect = [
        [],
        [{"namespace": "finance"}, {"namespace": "sales"}],
    ]
    provider = DatabricksMetadataProvider(executor=executor)
    result = provider.list_schemas(catalog="main")

    assert result == ["finance", "sales"]
    assert executor.execute.call_count == 2
    second_sql = executor.execute.call_args_list[1][0][0]
    assert second_sql.strip() == "SHOW SCHEMAS IN `main`"


def test_list_schemas_rejects_unsafe_catalog(executor):
    provider = DatabricksMetadataProvider(executor=executor)
    with pytest.raises(ValueError, match="Unsafe SQL identifier"):
        provider.list_schemas(catalog="bad-catalog; DROP TABLE")
